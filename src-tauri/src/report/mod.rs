//! Report generation: Markdown, JSON and CSV. Reports contain structure, metrics and findings
//! — never file contents.

pub mod docs;

use crate::analysis::model::{Analysis, EdgeKind, ImportTarget, Severity};
use crate::compare::Comparison;
use crate::error::{AppError, AppResult};
use crate::store::mapping::Mapping;
use serde::Deserialize;
use std::fmt::Write;

pub const ALL_SECTIONS: &[&str] =
    &["overview", "structure", "languages", "metrics", "dependencies", "cycles", "health", "documentation", "notes"];

pub const CSV_TABLES: &[&str] = &["files", "findings", "dependencies", "packages", "languages", "directories"];

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct ReportOptions {
    /// `markdown`, `json` or `csv`
    pub format: String,
    pub sections: Vec<String>,
    pub csv_table: String,
    /// Max rows per list in Markdown (full lists in JSON/CSV).
    pub max_items: usize,
    pub title: Option<String>,
}

impl Default for ReportOptions {
    fn default() -> Self {
        Self {
            format: "markdown".into(),
            sections: ALL_SECTIONS.iter().map(|s| s.to_string()).collect(),
            csv_table: "files".into(),
            max_items: 30,
            title: None,
        }
    }
}

pub struct ReportInput<'a> {
    pub analysis: &'a Analysis,
    pub mapping: Option<&'a Mapping>,
    pub comparison: Option<&'a Comparison>,
}

pub fn generate(input: &ReportInput, opts: &ReportOptions) -> AppResult<String> {
    if let Some(bad) = opts.sections.iter().find(|s| !ALL_SECTIONS.contains(&s.as_str()) && s.as_str() != "comparison")
    {
        return Err(AppError::validation("unknown_section", format!("unknown report section `{bad}`")));
    }
    match opts.format.as_str() {
        "markdown" => Ok(markdown(input, opts)),
        "json" => json(input, opts),
        "csv" => csv(input.analysis, &opts.csv_table),
        _ => Err(AppError::validation("unknown_format", "format must be markdown, json or csv")),
    }
}

fn human_bytes(b: u64) -> String {
    const U: [&str; 5] = ["B", "KB", "MB", "GB", "TB"];
    let mut v = b as f64;
    let mut i = 0;
    while v >= 1024.0 && i < U.len() - 1 {
        v /= 1024.0;
        i += 1;
    }
    if i == 0 {
        format!("{b} B")
    } else {
        format!("{v:.1} {}", U[i])
    }
}

/// Escape text placed inside a Markdown table cell.
fn md(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn sev(s: Severity) -> &'static str {
    match s {
        Severity::High => "High",
        Severity::Medium => "Medium",
        Severity::Low => "Low",
        Severity::Info => "Info",
    }
}

fn markdown(input: &ReportInput, o: &ReportOptions) -> String {
    let a = input.analysis;
    let has = |s: &str| o.sections.iter().any(|x| x == s);
    let n = o.max_items.clamp(5, 1000);
    let m = &a.metrics;
    let mut s = String::new();
    let title = o.title.clone().unwrap_or_else(|| format!("{} — Structure Report", a.meta.name));
    let _ = writeln!(s, "# {}\n", md(&title));
    let when = chrono::DateTime::from_timestamp(a.meta.started_at, 0)
        .map(|d| d.format("%Y-%m-%d %H:%M UTC").to_string())
        .unwrap_or_default();
    let _ = writeln!(
        s,
        "_Generated by Ivily Structura {} · analysis {when} · profile **{}** · {} ms_\n",
        crate::APP_VERSION,
        md(&a.meta.profile_name),
        a.meta.duration_ms
    );
    if a.meta.truncated {
        let _ = writeln!(
            s,
            "> **Note:** the scan stopped at the profile's entry limit; results cover part of the project.\n"
        );
    }

    if has("overview") {
        let _ = writeln!(s, "## Overview\n");
        let _ = writeln!(s, "| Metric | Value |\n|---|---|");
        let _ = writeln!(s, "| Files | {} |", m.total_files);
        let _ = writeln!(s, "| Directories | {} |", m.total_dirs);
        let _ = writeln!(s, "| Size | {} |", human_bytes(m.total_bytes));
        if a.meta.content_analyzed {
            let _ = writeln!(s, "| Source code lines (estimated) | {} |", m.source_code_lines);
        }
        let langs: Vec<String> = a.languages.iter().take(5).map(|l| l.name.clone()).collect();
        let _ = writeln!(s, "| Main languages | {} |", md(&langs.join(", ")));
        let fws: Vec<String> = a
            .ecosystems
            .iter()
            .flat_map(|e| e.frameworks.iter().map(|f| f.name.clone()))
            .collect::<std::collections::BTreeSet<_>>()
            .into_iter()
            .collect();
        if !fws.is_empty() {
            let _ = writeln!(s, "| Frameworks & tools | {} |", md(&fws.join(", ")));
        }
        let c = crate::health::count_by_severity(&a.findings);
        if a.meta.health_analyzed {
            let _ =
                writeln!(s, "| Findings (high / medium / low / info) | {} / {} / {} / {} |", c[3], c[2], c[1], c[0]);
        }
        s.push('\n');
    }

    if has("structure") {
        let st = &a.structure;
        let _ = writeln!(s, "## Structure\n");
        if !st.entry_points.is_empty() {
            let _ = writeln!(s, "**Entry points**\n");
            for e in st.entry_points.iter().take(n) {
                let _ = writeln!(s, "- `{}` — {}", e.path, md(&e.reason));
            }
            s.push('\n');
        }
        for (label, list) in [
            ("Source roots", &st.source_roots),
            ("Test roots", &st.test_roots),
            ("Documentation roots", &st.doc_roots),
            ("Asset roots", &st.asset_roots),
        ] {
            if !list.is_empty() {
                let _ = writeln!(
                    s,
                    "**{label}:** {}\n",
                    list.iter().map(|x| format!("`{x}`")).collect::<Vec<_>>().join(", ")
                );
            }
        }
        if !st.patterns.is_empty() {
            let _ =
                writeln!(s, "**Architectural patterns (hints)**\n\n| Pattern | Confidence | Evidence |\n|---|---|---|");
            for p in &st.patterns {
                let _ = writeln!(s, "| {} | {:?} | {} |", md(&p.name), p.confidence, md(&p.evidence.join("; ")));
            }
            s.push('\n');
        }
        let _ = writeln!(s, "**Files by role**\n\n| Role | Files |\n|---|---|");
        for (r, c) in &m.by_role {
            let _ = writeln!(s, "| {r} | {c} |");
        }
        s.push('\n');
        let top: Vec<_> = a.dirs.iter().filter(|d| d.depth == 1).collect();
        if !top.is_empty() {
            let _ = writeln!(s, "**Top-level directories**\n\n| Directory | Files | Size |\n|---|---|---|");
            for d in top.iter().take(n) {
                let _ = writeln!(s, "| `{}` | {} | {} |", d.path, d.total_files, human_bytes(d.total_bytes));
            }
            s.push('\n');
        }
    }

    if has("languages") && !a.languages.is_empty() {
        let _ =
            writeln!(s, "## Languages\n\n| Language | Files | Size | Lines | Analysis level |\n|---|---|---|---|---|");
        for l in a.languages.iter().take(n) {
            let _ = writeln!(
                s,
                "| {} | {} | {} | {} | {:?} |",
                md(&l.name),
                l.files,
                human_bytes(l.bytes),
                l.lines,
                l.support
            );
        }
        let _ = writeln!(s, "\n_Analysis level: **Lexical** = imports/symbols extracted by a comment-aware scanner; **Detected** = recognised by name only._\n");
    }

    if has("metrics") {
        let _ = writeln!(s, "## Metrics\n\n| Metric | Value | Kind |\n|---|---|---|");
        let rows: Vec<(&str, String, &str)> = vec![
            ("Total files", m.total_files.to_string(), "exact"),
            ("Total directories", m.total_dirs.to_string(), "exact"),
            ("Total size", human_bytes(m.total_bytes), "exact"),
            ("Max directory depth", m.max_depth.to_string(), "exact"),
            ("Text files analysed", m.text_files_analyzed.to_string(), "exact"),
            ("Total lines", m.total_lines.to_string(), "exact"),
            ("Blank lines", m.blank_lines.to_string(), "exact"),
            ("Code lines", m.code_lines.to_string(), "estimated"),
            ("Comment lines", m.comment_lines.to_string(), "estimated"),
            ("Average decision points per source file", format!("{:.1}", m.avg_complexity), "estimated"),
            ("Internal dependency edges", m.internal_edges.to_string(), "exact*"),
            ("External packages used", m.external_packages.to_string(), "exact*"),
            ("Declared dependencies", m.declared_dependencies.to_string(), "exact"),
            ("Circular dependencies", m.cycles.to_string(), "exact*"),
            ("Files skipped (sensitive)", m.skipped_sensitive.to_string(), "exact"),
            ("Files skipped (too large)", m.skipped_large.to_string(), "exact"),
        ];
        for (k, v, kind) in rows {
            let _ = writeln!(s, "| {k} | {v} | {kind} |");
        }
        let _ = writeln!(s, "\n_* exact over statically resolvable imports._\n");
        if !m.largest_files.is_empty() {
            let _ = writeln!(s, "**Largest files**\n\n| File | Size | Lines |\n|---|---|---|");
            for f in m.largest_files.iter().take(n.min(15)) {
                let _ = writeln!(s, "| `{}` | {} | {} |", f.path, human_bytes(f.bytes), f.lines);
            }
            s.push('\n');
        }
    }

    if has("dependencies") && a.meta.dependencies_analyzed {
        let g = &a.graph;
        let _ = writeln!(s, "## Dependencies\n");
        let _ = writeln!(
            s,
            "{} imports: {} internal, {} external, {} built-in, {} unresolved.\n",
            g.imports_total, g.imports_internal, g.imports_external, g.imports_builtin, g.imports_unresolved
        );
        for e in &a.ecosystems {
            let _ = writeln!(
                s,
                "- **{}** (`{}`) — {} declared dependencies{}",
                md(&e.name),
                e.manifest,
                e.dependencies.len(),
                e.package_manager.as_ref().map(|p| format!(", package manager: {p}")).unwrap_or_default()
            );
        }
        s.push('\n');
        let mut hubs: Vec<_> = a.files.iter().filter(|f| f.fan_in > 0).collect();
        hubs.sort_by_key(|f| std::cmp::Reverse(f.fan_in));
        if !hubs.is_empty() {
            let _ = writeln!(s, "**Most depended-upon files**\n\n| File | Used by | Uses |\n|---|---|---|");
            for f in hubs.iter().take(n.min(15)) {
                let _ = writeln!(s, "| `{}` | {} | {} |", f.path, f.fan_in, f.fan_out);
            }
            s.push('\n');
        }
        let used: Vec<_> = g.packages.iter().filter(|p| p.use_count > 0).collect();
        if !used.is_empty() {
            let _ = writeln!(
                s,
                "**External packages**\n\n| Package | Ecosystem | Imports | Files | Declared |\n|---|---|---|---|---|"
            );
            for p in used.iter().take(n) {
                let _ = writeln!(
                    s,
                    "| `{}` | {} | {} | {} | {} |",
                    md(&p.name),
                    p.ecosystem,
                    p.use_count,
                    p.users.len(),
                    if p.declared { "yes" } else { "**no**" }
                );
            }
            s.push('\n');
        }
    }

    if has("cycles") && a.meta.dependencies_analyzed {
        let _ = writeln!(s, "## Circular dependencies\n");
        if a.graph.cycles.is_empty() {
            let _ = writeln!(s, "No circular dependencies were found between statically resolved imports.\n");
        }
        for (i, c) in a.graph.cycles.iter().take(n).enumerate() {
            let chain: Vec<&str> =
                c.path.iter().chain(c.path.first()).map(|x| a.files[*x as usize].path.as_str()).collect();
            let _ = writeln!(s, "{}. **{} files** — `{}`", i + 1, c.files.len(), chain.join("` → `"));
        }
        s.push('\n');
    }

    if has("health") && a.meta.health_analyzed {
        let _ = writeln!(s, "## Architecture health\n");
        let _ = writeln!(s, "_Findings are indicators, not verdicts. Each lists its confidence and evidence. There is no aggregate score._\n");
        if a.findings.is_empty() {
            let _ = writeln!(s, "No findings for the enabled rules.\n");
        }
        for f in a.findings.iter().take(n * 2) {
            let _ = writeln!(s, "### [{}] {}\n", sev(f.severity), md(&f.title));
            let _ = writeln!(s, "- **Rule:** `{}` ({}) · **Confidence:** {:?}", f.rule, f.category, f.confidence);
            if let Some(mv) = &f.metric {
                let _ = writeln!(s, "- **Measured:** {} = {} (threshold {})", mv.name, mv.value, mv.threshold);
            }
            let _ = writeln!(s, "- {}", f.explanation);
            if !f.evidence.is_empty() {
                let _ = writeln!(s, "- **Evidence:**");
                for e in f.evidence.iter().take(10) {
                    let _ = writeln!(s, "  - {}", md(e));
                }
            }
            if !f.files.is_empty() {
                let shown: Vec<String> = f.files.iter().take(10).map(|x| format!("`{x}`")).collect();
                let more = if f.files.len() > 10 { format!(" and {} more", f.files.len() - 10) } else { String::new() };
                let _ = writeln!(s, "- **Affected:** {}{more}", shown.join(", "));
            }
            let _ = writeln!(s, "- **Suggestion:** {}\n", f.suggestion);
        }
    }

    if has("documentation") {
        let d = docs::overview(a);
        let _ = writeln!(s, "## Documentation\n");
        let _ = writeln!(
            s,
            "- README: {}",
            d.readme.as_deref().map(|r| format!("`{r}`")).unwrap_or_else(|| "**missing**".into())
        );
        let _ = writeln!(
            s,
            "- README files: {} · Markdown files: {} · documentation lines: {}",
            d.readmes.len(),
            d.markdown_files,
            d.doc_lines
        );
        if !d.doc_roots.is_empty() {
            let _ = writeln!(
                s,
                "- Documentation folders: {}",
                d.doc_roots.iter().map(|x| format!("`{x}`")).collect::<Vec<_>>().join(", ")
            );
        }
        for (k, v) in &d.community {
            let _ = writeln!(
                s,
                "- {}: {}",
                k.replace('_', " "),
                v.as_deref().map(|x| format!("`{x}`")).unwrap_or_else(|| "not found".into())
            );
        }
        if !d.api_docs.is_empty() {
            let _ = writeln!(
                s,
                "- API documentation: {}",
                d.api_docs.iter().take(10).map(|x| format!("`{x}`")).collect::<Vec<_>>().join(", ")
            );
        }
        if !d.undocumented_areas.is_empty() {
            let _ = writeln!(
                s,
                "- Areas with 10+ source files and no documentation: {}",
                d.undocumented_areas.iter().map(|x| format!("`{x}`")).collect::<Vec<_>>().join(", ")
            );
        }
        s.push('\n');
    }

    if has("notes") {
        if let Some(mp) = input.mapping {
            if !(mp.notes.is_empty() && mp.annotations.is_empty() && mp.layers.is_empty()) {
                let _ = writeln!(s, "## Project notes & mapping\n");
                if !mp.layers.is_empty() {
                    let _ = writeln!(
                        s,
                        "**Layers (top → bottom):** {}\n",
                        mp.layers.iter().map(|l| l.name.clone()).collect::<Vec<_>>().join(" → ")
                    );
                }
                for nt in &mp.notes {
                    let _ = writeln!(s, "### {}\n\n{}\n", md(&nt.title), nt.body);
                }
                let annotated: Vec<_> = mp
                    .annotations
                    .iter()
                    .filter(|x| !x.label.is_empty() || !x.note.is_empty() || x.important)
                    .collect();
                if !annotated.is_empty() {
                    let _ = writeln!(s, "| Path | Label | Note |\n|---|---|---|");
                    for an in annotated.iter().take(n * 2) {
                        let _ = writeln!(
                            s,
                            "| `{}`{} | {} | {} |",
                            an.path,
                            if an.important { " ★" } else { "" },
                            md(&an.label),
                            md(&an.note)
                        );
                    }
                    s.push('\n');
                }
            }
        }
    }

    if let Some(c) = input.comparison {
        let _ = writeln!(s, "## Comparison: {} → {}\n", md(&c.before_label), md(&c.after_label));
        let _ = writeln!(s, "| Metric | Before | After | Change | Kind |\n|---|---|---|---|---|");
        for d in &c.metrics {
            let _ = writeln!(s, "| {} | {} | {} | {:+} | {} |", d.name, d.before, d.after, d.change, d.kind);
        }
        let _ = writeln!(
            s,
            "\n- Files: +{} / −{} · changed: {}",
            c.files.added_count, c.files.removed_count, c.changed_files_count
        );
        let _ =
            writeln!(s, "- Modules added: {} · removed: {}", c.modules.added.join(", "), c.modules.removed.join(", "));
        let _ = writeln!(
            s,
            "- Packages added: {} · removed: {}",
            c.packages.added.join(", "),
            c.packages.removed.join(", ")
        );
        let _ = writeln!(s, "- New cycles: {} · resolved cycles: {}", c.cycles_new.len(), c.cycles_resolved.len());
        let _ = writeln!(
            s,
            "- New findings: {} · resolved findings: {}\n",
            c.findings_new.len(),
            c.findings_resolved.len()
        );
    }
    s
}

fn json(input: &ReportInput, o: &ReportOptions) -> AppResult<String> {
    let a = input.analysis;
    let has = |s: &str| o.sections.iter().any(|x| x == s);
    let mut root = serde_json::Map::new();
    root.insert("format".into(), "ivily-structura-report".into());
    root.insert("version".into(), 1.into());
    root.insert("generator".into(), format!("Ivily Structura {}", crate::APP_VERSION).into());
    root.insert("meta".into(), serde_json::to_value(&a.meta)?);
    if has("overview") {
        root.insert("summary".into(), serde_json::to_value(crate::store::projects::summary_of(a))?);
    }
    if has("structure") {
        root.insert("structure".into(), serde_json::to_value(&a.structure)?);
        root.insert("ecosystems".into(), serde_json::to_value(&a.ecosystems)?);
        root.insert("directories".into(), serde_json::to_value(&a.dirs)?);
    }
    if has("languages") {
        root.insert("languages".into(), serde_json::to_value(&a.languages)?);
    }
    if has("metrics") {
        root.insert("metrics".into(), serde_json::to_value(&a.metrics)?);
    }
    if has("dependencies") {
        let nodes: Vec<&str> = a.files.iter().map(|f| f.path.as_str()).collect();
        let edges: Vec<serde_json::Value> = a
            .graph
            .edges
            .iter()
            .map(|e| serde_json::json!({"from": nodes[e.from as usize], "to": nodes[e.to as usize], "kind": if e.kind == EdgeKind::Uses {"uses"} else {"contains"}, "count": e.count}))
            .collect();
        root.insert(
            "dependencies".into(),
            serde_json::json!({
                "edges": edges,
                "packages": a.graph.packages,
                "imports": { "total": a.graph.imports_total, "internal": a.graph.imports_internal, "external": a.graph.imports_external, "builtin": a.graph.imports_builtin, "unresolved": a.graph.imports_unresolved },
                "resolutionMethods": a.graph.resolution_methods,
            }),
        );
    }
    if has("cycles") {
        let cycles: Vec<Vec<&str>> = a
            .graph
            .cycles
            .iter()
            .map(|c| c.path.iter().map(|i| a.files[*i as usize].path.as_str()).collect())
            .collect();
        root.insert("cycles".into(), serde_json::to_value(cycles)?);
    }
    if has("health") {
        root.insert("findings".into(), serde_json::to_value(&a.findings)?);
    }
    if has("documentation") {
        root.insert("documentation".into(), serde_json::to_value(docs::overview(a))?);
    }
    if has("notes") {
        if let Some(m) = input.mapping {
            root.insert("mapping".into(), serde_json::to_value(m)?);
        }
    }
    if let Some(c) = input.comparison {
        root.insert("comparison".into(), serde_json::to_value(c)?);
    }
    Ok(serde_json::to_string_pretty(&serde_json::Value::Object(root))?)
}

/// CSV cell: quoted, and neutralised against spreadsheet formula injection.
fn cell(s: &str) -> String {
    let s = if s.starts_with(['=', '+', '-', '@', '\t', '\r']) { format!("'{s}") } else { s.to_string() };
    format!("\"{}\"", s.replace('"', "\"\""))
}

fn csv(a: &Analysis, table: &str) -> AppResult<String> {
    let mut out = String::new();
    let mut row = |cells: Vec<String>| {
        out.push_str(&cells.iter().map(|c| cell(c)).collect::<Vec<_>>().join(","));
        out.push_str("\r\n");
    };
    match table {
        "files" => {
            row([
                "path",
                "role",
                "language",
                "bytes",
                "lines",
                "code_lines_est",
                "complexity_est",
                "fan_in",
                "fan_out",
                "external_deps",
                "symbols",
                "skipped",
            ]
            .map(String::from)
            .to_vec());
            for f in &a.files {
                row(vec![
                    f.path.clone(),
                    f.role().as_str().into(),
                    f.language.clone().unwrap_or_default(),
                    f.size.to_string(),
                    f.lines.map(|l| l.total.to_string()).unwrap_or_default(),
                    f.lines.map(|l| l.code.to_string()).unwrap_or_default(),
                    f.complexity.map(|c| c.to_string()).unwrap_or_default(),
                    f.fan_in.to_string(),
                    f.fan_out.to_string(),
                    f.external_deps.to_string(),
                    f.symbol_count.to_string(),
                    f.skipped.clone().unwrap_or_default(),
                ]);
            }
        }
        "findings" => {
            row(["severity", "confidence", "rule", "category", "title", "files", "suggestion"]
                .map(String::from)
                .to_vec());
            for f in &a.findings {
                row(vec![
                    sev(f.severity).into(),
                    format!("{:?}", f.confidence),
                    f.rule.clone(),
                    f.category.clone(),
                    f.title.clone(),
                    f.files.join("; "),
                    f.suggestion.clone(),
                ]);
            }
        }
        "dependencies" => {
            row(["from", "to", "kind", "count", "first_line"].map(String::from).to_vec());
            for e in &a.graph.edges {
                row(vec![
                    a.files[e.from as usize].path.clone(),
                    a.files[e.to as usize].path.clone(),
                    if e.kind == EdgeKind::Uses { "uses".into() } else { "contains".into() },
                    e.count.to_string(),
                    e.line.to_string(),
                ]);
            }
            // External imports as well.
            for f in &a.files {
                for i in &f.imports {
                    if let ImportTarget::External { name, ecosystem } = &i.target {
                        row(vec![
                            f.path.clone(),
                            format!("{ecosystem}:{name}"),
                            "external".into(),
                            "1".into(),
                            i.line.to_string(),
                        ]);
                    }
                }
            }
        }
        "packages" => {
            row(["ecosystem", "package", "declared", "kind", "version", "manifest", "imports", "files"]
                .map(String::from)
                .to_vec());
            for p in &a.graph.packages {
                row(vec![
                    p.ecosystem.clone(),
                    p.name.clone(),
                    p.declared.to_string(),
                    p.declared_kind.clone().unwrap_or_default(),
                    p.version.clone().unwrap_or_default(),
                    p.manifest.clone().unwrap_or_default(),
                    p.use_count.to_string(),
                    p.users.len().to_string(),
                ]);
            }
        }
        "languages" => {
            row(["language", "category", "support", "files", "bytes", "lines", "code_lines_est"]
                .map(String::from)
                .to_vec());
            for l in &a.languages {
                row(vec![
                    l.name.clone(),
                    format!("{:?}", l.category),
                    format!("{:?}", l.support),
                    l.files.to_string(),
                    l.bytes.to_string(),
                    l.lines.to_string(),
                    l.code_lines.to_string(),
                ]);
            }
        }
        "directories" => {
            row(["path", "depth", "direct_files", "direct_dirs", "total_files", "total_bytes", "total_lines"]
                .map(String::from)
                .to_vec());
            for d in &a.dirs {
                row(vec![
                    d.path.clone(),
                    d.depth.to_string(),
                    d.direct_files.to_string(),
                    d.direct_dirs.to_string(),
                    d.total_files.to_string(),
                    d.total_bytes.to_string(),
                    d.total_lines.to_string(),
                ]);
            }
        }
        _ => return Err(AppError::validation("unknown_table", format!("unknown CSV table `{table}`"))),
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::analysis::tests::{analyze_tree, web_project};

    #[test]
    fn markdown_json_csv_reports() {
        let t = web_project();
        let a = analyze_tree(&t, "full");
        let input = ReportInput { analysis: &a, mapping: None, comparison: None };
        let md = generate(&input, &ReportOptions::default()).unwrap();
        for h in [
            "## Overview",
            "## Structure",
            "## Languages",
            "## Metrics",
            "## Dependencies",
            "## Circular dependencies",
            "## Architecture health",
            "## Documentation",
        ] {
            assert!(md.contains(h), "missing {h}");
        }
        assert!(md.contains("estimated"));
        assert!(md.contains("src/lib/a.js"));

        let only =
            generate(&input, &ReportOptions { sections: vec!["languages".into()], ..Default::default() }).unwrap();
        assert!(only.contains("## Languages") && !only.contains("## Metrics"));

        let js = generate(&input, &ReportOptions { format: "json".into(), ..Default::default() }).unwrap();
        let v: serde_json::Value = serde_json::from_str(&js).unwrap();
        assert_eq!(v["format"], "ivily-structura-report");
        assert!(v["dependencies"]["edges"].as_array().unwrap().iter().any(|e| e["from"] == "src/main.jsx"));
        assert!(!v["findings"].as_array().unwrap().is_empty());

        for table in CSV_TABLES {
            let csv = generate(
                &input,
                &ReportOptions { format: "csv".into(), csv_table: table.to_string(), ..Default::default() },
            )
            .unwrap();
            assert!(csv.lines().count() >= 2, "table {table} has rows");
        }
        assert!(generate(&input, &ReportOptions { format: "pdf".into(), ..Default::default() }).is_err());
        assert!(generate(&input, &ReportOptions { sections: vec!["bogus".into()], ..Default::default() }).is_err());
        // Reports never include file contents.
        assert!(!md.contains("same content"));
    }

    #[test]
    fn csv_cells_are_escaped_and_neutralised() {
        assert_eq!(cell("a\"b"), "\"a\"\"b\"");
        assert_eq!(cell("=SUM(A1)"), "\"'=SUM(A1)\"");
        assert_eq!(cell("@cmd"), "\"'@cmd\"");
        assert_eq!(cell("plain"), "\"plain\"");
    }
}
